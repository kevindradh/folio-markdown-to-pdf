import { test, expect } from '@playwright/test'

const dialog = (page: import('@playwright/test').Page) => page.locator('[role="dialog"].coachmark')

test('first visit tour covers the writing workflow, remembers completion and reopens without altering content', async ({ page }, testInfo) => {
  await page.goto('/')
  const tour = dialog(page)
  await expect(tour).toBeVisible()
  await expect(tour).toContainText('Tur aplikasi · 1 dari 5')
  const before = await page.locator('#markdown-editor').inputValue()
  await expect(tour.getByRole('button', { name: 'Lanjut', exact: true })).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(tour.getByRole('button', { name: 'Lewati', exact: true })).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await expect(tour.getByRole('button', { name: 'Lanjut', exact: true })).toBeFocused()
  await page.screenshot({ path: testInfo.outputPath('coachmark-desktop.png') })
  await tour.getByRole('button', { name: 'Lanjut', exact: true }).click()
  await expect(tour).toContainText('Lihat hasilnya langsung')
  await tour.getByRole('button', { name: 'Kembali', exact: true }).click()
  await expect(tour).toContainText('1 dari 5')
  for (let i = 0; i < 4; i++) await tour.getByRole('button', { name: 'Lanjut', exact: true }).click()
  await expect(tour).toContainText('Jadikan PDF')
  await tour.getByRole('button', { name: 'Mulai menulis', exact: true }).click()
  await expect(tour).toBeHidden()
  expect(await page.evaluate(() => localStorage.getItem('folio:tour:v1'))).toBe('done')
  await expect(page.locator('#markdown-editor')).toHaveValue(before)
  await page.reload()
  await expect(page.locator('#markdown-editor')).toHaveValue(before)
  await expect(tour).toHaveCount(0)
  await page.getByRole('button', { name: 'Pratinjau', exact: true }).click()
  await page.getByRole('button', { name: 'Panduan Markdown', exact: true }).click()
  await page.getByRole('button', { name: 'Tur aplikasi', exact: true }).click()
  await expect(tour).toContainText('1 dari 5')
  await expect(page.locator('.workspace')).toHaveClass(/view-split/)
  await page.keyboard.press('Escape')
  await expect(tour).toHaveCount(0)
  await expect(page.locator('.workspace')).toHaveClass(/view-preview/)
  await expect(page.getByRole('button', { name: 'Panduan Markdown', exact: true })).toBeFocused()
})

test('mobile tour stays within the viewport, supports skip and is excluded from print', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  const tour = dialog(page)
  await expect(tour).toBeVisible()
  for (let i = 0; i < 5; i++) {
    await expect(tour).toContainText(`${i + 1} dari 5`)
    await expect.poll(() => tour.evaluate(el => {
      const r = el.getBoundingClientRect()
      return r.left >= 0 && r.right <= innerWidth && r.top >= 0 && r.bottom <= innerHeight && el.scrollWidth <= el.clientWidth
    })).toBe(true)
    await page.screenshot({ path: testInfo.outputPath(`coachmark-mobile-${i + 1}.png`) })
    if (i < 4) await tour.getByRole('button', { name: 'Lanjut', exact: true }).click()
  }
  await page.emulateMedia({ media: 'print' })
  await expect(tour).toBeHidden()
  await page.emulateMedia({ media: 'screen' })
  await tour.getByRole('button', { name: 'Lewati', exact: true }).click()
  expect(await page.evaluate(() => localStorage.getItem('folio:tour:v1'))).toBe('done')
  await page.reload()
  await expect(page.locator('#markdown-editor')).toBeVisible()
  await expect(tour).toHaveCount(0)
})

test('returning users are not interrupted and manual tour works with blocked storage', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('folio:draft:v1', JSON.stringify({ version: 1, text: '# Tulisan saya', name: 'Milik saya', paper: 'A4', font: 'Literary', margin: 'Normal', codeTheme: 'light' })))
  await page.goto('/')
  await expect(page.locator('#markdown-editor')).toHaveValue('# Tulisan saya')
  await expect(dialog(page)).toHaveCount(0)
  await page.evaluate(() => {
    Storage.prototype.setItem = () => { throw new DOMException('Blocked', 'SecurityError') }
  })
  await page.getByRole('button', { name: 'Panduan Markdown', exact: true }).click()
  await page.getByRole('button', { name: 'Tur aplikasi', exact: true }).click()
  await expect(dialog(page)).toBeVisible()
  await dialog(page).getByRole('button', { name: 'Lewati', exact: true }).click()
  await expect(dialog(page)).toHaveCount(0)
  await expect(page.locator('#markdown-editor')).toHaveValue('# Tulisan saya')
})
