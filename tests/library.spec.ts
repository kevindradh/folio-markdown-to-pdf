import { test, expect, type Page } from '@playwright/test'
import { DRAFT_KEY } from '../src/lib/document-draft'
import { LIBRARY_DB, MAX_LIBRARY_BYTES, type Project, type LibraryDocument, type DocumentVersion } from '../src/lib/document-library'

async function stored(page: Page) {
  return page.evaluate(async name => {
    const db = await new Promise<IDBDatabase>((resolve, reject) => { const request = indexedDB.open(name); request.onsuccess = () => resolve(request.result); request.onerror = () => reject(request.error) })
    const tx = db.transaction(['projects', 'documents', 'versions', 'meta'])
    const data = await Promise.all(['projects', 'documents', 'versions', 'meta'].map(store => new Promise<unknown[]>(resolve => { const request = tx.objectStore(store).getAll(); request.onsuccess = () => resolve(request.result) })))
    db.close(); return { projects: data[0] as Project[], documents: data[1] as LibraryDocument[], versions: data[2] as DocumentVersion[], meta: data[3][0] as { bytes: number; activeId: string } }
  }, LIBRARY_DB)
}

async function project(page: Page, name: string) {
  await page.getByRole('button', { name: 'Project', exact: true }).click()
  await page.getByRole('button', { name: 'Project baru', exact: true }).click()
  await page.getByLabel('Nama project', { exact: true }).fill(name)
  await page.getByRole('button', { name: 'Simpan', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Project baru', exact: true })).toBeHidden()
}

async function newDocument(page: Page, name: string, text: string) {
  await page.getByRole('button', { name: 'Dokumen baru', exact: true }).click()
  await page.locator('#document-name').fill(name)
  await page.locator('#markdown-editor').fill(text)
  await expect(page.locator('#draft-status')).toHaveText('Draft tersimpan')
}

test('legacy draft migrates once with settings and empty text intact', async ({ page }) => {
  await page.addInitScript(key => localStorage.setItem(key, JSON.stringify({ version: 1, text: '', name: 'Draft lama 🌿', paper: 'Letter', font: 'Modern', margin: 'Lebar', codeTheme: 'dark' })), DRAFT_KEY)
  await page.goto('/')
  await expect(page.locator('#markdown-editor')).toHaveValue('')
  await expect(page.locator('#document-name')).toHaveValue('Draft lama 🌿')
  await expect(page.locator('#paper-size')).toContainText('Letter')
  await expect(page.locator('#draft-status')).toHaveText('Draft tersimpan')
  await page.reload()
  const value = await stored(page)
  expect(value.projects).toHaveLength(1)
  expect(value.projects[0].name).toBe('Umum')
  expect(value.documents).toHaveLength(1)
  expect(value.documents[0].draft).toMatchObject({ text: '', name: 'Draft lama 🌿', font: 'Modern', margin: 'Lebar', codeTheme: 'dark' })
  expect(value.versions).toHaveLength(1)
})

