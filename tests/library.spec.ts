test('manual and automatic history restore contents and settings while retaining pre-restore changes', async ({ page }) => {
  await page.goto('/')
  await page.locator('#markdown-editor').fill('# Versi satu\n\nAwal 🌿')
  await page.locator('#document-name').fill('Versi pertama')
  await page.getByRole('button', { name: 'Riwayat', exact: true }).click()
  await page.getByRole('button', { name: 'Simpan versi', exact: true }).click()
  await expect(page.getByText('Versi saat ini tersimpan.', { exact: true })).toBeVisible()
  const first = (await stored(page)).versions.find(item => item.draft.text === '# Versi satu\n\nAwal 🌿')!
  await page.getByRole('dialog', { name: 'Riwayat versi', exact: true }).getByRole('button', { name: 'Close', exact: true }).click()
  await page.locator('#markdown-editor').fill('# Versi dua\n\nPerubahan terbaru')
  await page.locator('#paper-size').click()
  await page.getByRole('option', { name: 'Letter', exact: true }).click()
  await expect.poll(async () => (await stored(page)).versions.some(item => item.kind === 'automatic' && item.draft.text.includes('Versi dua')), { timeout: 25_000 }).toBe(true)
  await page.locator('#markdown-editor').fill('# Sebelum pulih\n\nJangan hilang')
  await page.getByRole('button', { name: 'Riwayat', exact: true }).click()
  const versions = (await stored(page)).versions.sort((a, b) => b.createdAt - a.createdAt)
  await page.getByRole('navigation', { name: 'Daftar versi' }).getByRole('button').nth(versions.findIndex(item => item.id === first.id)).click()
  await expect(page.getByLabel(/^Isi versi/)).toHaveValue('# Versi satu\n\nAwal 🌿')
  await page.getByRole('button', { name: 'Pulihkan versi ini', exact: true }).click()
  await page.getByRole('button', { name: 'Pulihkan', exact: true }).click()
  await expect(page.locator('#markdown-editor')).toHaveValue('# Versi satu\n\nAwal 🌿')
  await expect(page.locator('#paper-size')).toContainText('A4')
  expect((await stored(page)).versions.some(item => item.kind === 'before-restore' && item.draft.text.includes('Jangan hilang'))).toBe(true)
  await page.reload()
  await expect(page.locator('#markdown-editor')).toHaveValue('# Versi satu\n\nAwal 🌿')
})

