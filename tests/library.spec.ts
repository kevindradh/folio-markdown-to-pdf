test('bounded history and content budget do not discard current documents', async ({ page }) => {
  await page.goto('/')
  await expect(page.locator('#draft-status')).toHaveText('Draft tersimpan')
  // Seed the metadata near its budget to exercise history trimming on the next save.
  await page.evaluate(async ({ name, maximum }) => {
    const db = await new Promise<IDBDatabase>(resolve => { const request = indexedDB.open(name); request.onsuccess = () => resolve(request.result) })
    const tx = db.transaction('meta', 'readwrite'); const store = tx.objectStore('meta')
    const request = store.get('library')
    request.onsuccess = () => store.put({ ...request.result, bytes: maximum - 5 })
    await new Promise<void>(resolve => { tx.oncomplete = () => resolve() }); db.close()
  }, { name: LIBRARY_DB, maximum: MAX_LIBRARY_BYTES })
  await page.locator('#markdown-editor').fill('# Plus long content\n' + 'Kalimat. '.repeat(150))
  await expect(page.locator('#draft-status')).toHaveText('Draft tersimpan')
  const value = await stored(page)
  expect(value.documents[0].draft.text).toContain('Plus long content')
  expect(value.meta.bytes).toBeLessThanOrEqual(MAX_LIBRARY_BYTES)
})

