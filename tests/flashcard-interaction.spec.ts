import { test, expect } from './fixtures'

test.use({ hasTouch: true, viewport: { width: 390, height: 844 } })
test.beforeEach(async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('latih:guide-completed:v1', 'true'))
  await page.goto('/latih/koleksi')
  await page.getByRole('button', { name: 'Impor soal', exact: true }).click()
  await page.getByLabel('JSON latihan').fill(JSON.stringify({ title: 'Interaksi kartu', type: 'flashcard', questions: [
    { question: 'Kartu pertama\n\n[Sumber](https://example.com)', answer: 'Jawaban pertama', hint: 'Petunjuk pertama', explanation: 'Penjelasan pertama' },
    { question: 'Kartu kedua', answer: 'Jawaban kedua', hint: 'Petunjuk kedua', explanation: 'Penjelasan kedua' },
    { question: 'Kartu ketiga', answer: 'Jawaban ketiga', hint: 'Petunjuk ketiga', explanation: 'Penjelasan ketiga' },
  ] }))
  await page.getByRole('button', { name: 'Tambahkan koleksi', exact: true }).click()
  await page.locator('[data-slot="card"]').filter({ hasText: 'Interaksi kartu' }).getByRole('button', { name: 'Mulai latihan' }).click()
})

test('Space reveals then advances without focusing the card or activating focused footer controls', async ({ page }) => {
  const rotor = page.locator('.latih-flashcard-rotor')
  await page.reload()
  await expect(page.getByRole('region', { name: 'Pertanyaan kartu', exact: true })).toContainText('Kartu pertama')
  expect(await page.evaluate(() => document.activeElement?.classList.contains('latih-flashcard-stage'))).toBe(false)
  await page.keyboard.down('Space')
  await expect(rotor).toHaveAttribute('data-revealed', 'true')
  await page.keyboard.down('Space')
  await page.keyboard.up('Space')
  await expect(page.locator('.latih-quiz-title')).toContainText('Kartu 1 dari 3')
  await page.getByRole('button', { name: 'Penjelasan', exact: true }).focus()
  await page.keyboard.press('Space')
  await expect(page.locator('.latih-quiz-title')).toContainText('Kartu 2 dari 3')
  await expect(rotor).toHaveAttribute('data-revealed', 'false')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('button', { name: 'Petunjuk', exact: true }).focus()
  await page.keyboard.press('Space')
  await expect(rotor).toHaveAttribute('data-revealed', 'true')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('button', { name: 'Berikutnya', exact: true }).focus()
  await page.keyboard.press('Space')
  await expect(page.locator('.latih-quiz-title')).toContainText('Kartu 3 dari 3')
  await expect(rotor).toHaveAttribute('data-revealed', 'false')
})

test('touching cards uses the same reveal/next action while links, drag and sheets stay independent', async ({ page }) => {
  const activeCard = page.locator('.latih-flashcard[data-active=true]')
  const rotor = page.locator('.latih-flashcard-rotor')
  // Keep this navigation test local while verifying a link tap never turns the card.
  await page.getByRole('link', { name: 'Sumber', exact: true }).evaluate(element => element.addEventListener('click', event => event.preventDefault()))
  await page.getByRole('link', { name: 'Sumber', exact: true }).tap()
  await expect(rotor).toHaveAttribute('data-revealed', 'false')
  await activeCard.dispatchEvent('pointerdown', { clientX: 100, clientY: 200 })
  await activeCard.dispatchEvent('pointermove', { clientX: 100, clientY: 300 })
  await activeCard.dispatchEvent('click')
  await expect(rotor).toHaveAttribute('data-revealed', 'false')
  await activeCard.tap()
  await expect(rotor).toHaveAttribute('data-revealed', 'true')
  await page.getByRole('button', { name: 'Lihat pertanyaan', exact: true }).tap()
  await expect(rotor).toHaveAttribute('data-revealed', 'false')
  await expect(page.locator('.latih-quiz-title')).toContainText('Kartu 1 dari 3')
  await activeCard.tap()
  await activeCard.tap()
  await expect(page.locator('.latih-quiz-title')).toContainText('Kartu 2 dari 3')
  await expect(rotor).toHaveAttribute('data-revealed', 'false')
  await page.getByRole('button', { name: 'Petunjuk', exact: true }).tap()
  const hint = page.getByRole('dialog', { name: 'Petunjuk', exact: true })
  await expect(hint).toBeVisible()
  await hint.getByRole('button', { name: 'Kembali ke kartu', exact: true }).focus()
  await page.keyboard.press('Space')
  await expect(hint).toBeHidden()
  await expect(rotor).toHaveAttribute('data-revealed', 'false')
  await page.keyboard.press('Space')
  await expect(rotor).toHaveAttribute('data-revealed', 'true')
  await page.getByRole('button', { name: 'Penjelasan', exact: true }).tap()
  const explanation = page.getByRole('dialog', { name: 'Penjelasan', exact: true })
  await expect(explanation).toContainText('Penjelasan kedua')
  await explanation.getByRole('button', { name: 'Kembali ke kartu', exact: true }).tap()
  await expect(explanation).toBeHidden()
  await activeCard.tap()
  await expect(page.locator('.latih-quiz-title')).toContainText('Kartu 3 dari 3')
  await activeCard.tap()
  await activeCard.tap()
  await expect(page.getByText('3 kartu sudah dipelajari.', { exact: true })).toBeVisible()
})
