import { test, expect } from './fixtures'

test('inline and block themes are independent across preview, print, reload and history', async ({ page }, testInfo) => {
  await page.goto('/')
  await page.locator('#markdown-editor').fill('Inline `const value = 42`\n\n```javascript\nconst value = 42\nconsole.log(value)\n```')
  const inline = page.getByRole('group', { name: 'Kode inline', exact: true })
  const block = page.getByRole('group', { name: 'Blok kode', exact: true })
  const inlineCode = page.locator('.paper-pages p > code').first()
  const blockCode = page.locator('.paper-pages pre > code').first()
  const background = (locator: typeof inlineCode) => locator.evaluate(el => getComputedStyle(el).backgroundColor)
  await expect(page.getByRole('button', { name: 'Ekspor PDF', exact: true })).toBeEnabled()
  const light = await background(inlineCode)
  await block.getByRole('button', { name: 'Gelap', exact: true }).click()
  await expect.poll(() => background(blockCode)).toBe('rgb(30, 41, 59)')
  expect(await background(inlineCode)).toBe(light)
  await inline.getByRole('button', { name: 'Gelap', exact: true }).click()
  await block.getByRole('button', { name: 'Terang', exact: true }).click()
  await expect.poll(() => background(inlineCode)).toBe('rgb(30, 41, 59)')
  expect(await background(blockCode)).toBe(light)
  await expect(page.locator('#draft-status')).toHaveText('Draft tersimpan')
  await page.reload()
  await expect(inline.getByRole('button', { name: 'Gelap', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(block.getByRole('button', { name: 'Terang', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect.poll(() => background(inlineCode)).toBe('rgb(30, 41, 59)')
  await page.emulateMedia({ media: 'print' })
  expect(await background(inlineCode)).toBe('rgb(30, 41, 59)')
  expect(await background(blockCode)).toBe(light)
  await page.emulateMedia({ media: 'screen' })
  await page.getByRole('button', { name: 'Riwayat', exact: true }).click()
  await page.getByRole('button', { name: 'Simpan versi', exact: true }).click()
  await page.getByRole('dialog', { name: 'Riwayat versi', exact: true }).getByRole('button', { name: 'Close', exact: true }).click()
  await inline.getByRole('button', { name: 'Terang', exact: true }).click()
  await page.getByRole('button', { name: 'Riwayat', exact: true }).click()
  await page.getByRole('button', { name: 'Pulihkan versi ini', exact: true }).click()
  await page.getByRole('button', { name: 'Pulihkan', exact: true }).click()
  await expect(inline.getByRole('button', { name: 'Gelap', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(block.getByRole('button', { name: 'Terang', exact: true })).toHaveAttribute('aria-pressed', 'true')
  for (const width of [730, 900, 1280, 390]) {
    await page.setViewportSize({ width, height: 844 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  }
  await block.scrollIntoViewIfNeeded()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('code-themes-mobile.png') })
})

test('legacy themes apply to both code types and changing the block keeps the inline theme', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('folio:draft:v1', JSON.stringify({ version: 1, text: 'Inline `const x = 1`\n\n```js\nconst x = 1\n```', name: 'Lama', paper: 'A4', font: 'Literary', margin: 'Normal', codeTheme: 'dark' })))
  await page.goto('/')
  const inline = page.getByRole('group', { name: 'Kode inline', exact: true })
  const block = page.getByRole('group', { name: 'Blok kode', exact: true })
  await expect(inline.getByRole('button', { name: 'Gelap', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(block.getByRole('button', { name: 'Gelap', exact: true })).toHaveAttribute('aria-pressed', 'true')
  // Simulate an IndexedDB record written by the old build without the new property.
  await page.evaluate(async () => {
    const db = await new Promise<IDBDatabase>((resolve, reject) => { const r = indexedDB.open('folio-library'); r.onsuccess = () => resolve(r.result); r.onerror = () => reject(r.error) })
    await new Promise<void>((resolve, reject) => {
      const tx = db.transaction('documents', 'readwrite'); const store = tx.objectStore('documents'); const r = store.openCursor()
      r.onsuccess = () => { if (r.result) { const value = r.result.value; delete value.draft.inlineCodeTheme; r.result.update(value); r.result.continue() } }
      tx.oncomplete = () => resolve(); tx.onabort = () => reject(tx.error)
    }); db.close()
  })
  await page.reload()
  await block.getByRole('button', { name: 'Terang', exact: true }).click()
  await expect(inline.getByRole('button', { name: 'Gelap', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('#draft-status')).toHaveText('Draft tersimpan')
  await page.reload()
  await expect(inline.getByRole('button', { name: 'Gelap', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(block.getByRole('button', { name: 'Terang', exact: true })).toHaveAttribute('aria-pressed', 'true')
})
