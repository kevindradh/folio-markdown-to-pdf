import { test, expect } from '@playwright/test'

test('new users can only read for sixty seconds, then completion persists', async ({ page }, testInfo) => {
  await page.clock.install()
  await page.goto('/latih/#koleksi')
  await expect(page.getByRole('heading', { name: 'Sebelum mulai belajar' })).toBeVisible()
  await expect(page.getByRole('navigation')).toHaveCount(0)
  await expect(page.getByRole('button')).toHaveCount(1)
  const proceed = page.getByRole('button', { name: 'Saya sudah membaca' })
  await expect(proceed).toBeDisabled()
  await page.clock.runFor(58_000)
  await expect(proceed).toBeDisabled()
  await page.evaluate(() => { location.hash = 'template' })
  await expect(page.getByRole('heading', { name: 'Template soal', exact: true })).toHaveCount(0)
  await page.clock.runFor(2_500)
  await expect(proceed).toBeEnabled()
  await proceed.click()
  await expect(page.getByRole('heading', { name: 'Template soal', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Sebelum mulai belajar' })).toHaveCount(0)
  await page.goto('/')
  await page.goto('/latih/')
  await expect(page.getByRole('heading', { name: 'Beranda', exact: true })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('completed-guide.png') })
})

test('reading time pauses in a hidden tab and survives refresh', async ({ page }) => {
  await page.clock.install()
  await page.goto('/latih/#panduan')
  await expect(page.getByRole('heading', { name: 'Sebelum mulai belajar' })).toBeVisible()
  await page.clock.runFor(30_000)
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Sebelum mulai belajar' })).toBeVisible()
  const before = Number(await page.getByRole('progressbar').getAttribute('value'))
  expect(before).toBeGreaterThanOrEqual(30_000)
  await page.evaluate(() => { Object.defineProperty(document, 'visibilityState', { configurable: true, value: 'hidden' }); document.dispatchEvent(new Event('visibilitychange')) })
  await page.clock.runFor(60_000)
  await expect(page.getByRole('button', { name: 'Saya sudah membaca' })).toBeDisabled()
  const after = Number(await page.getByRole('progressbar').getAttribute('value'))
  expect(after - before).toBeLessThan(1000)
  await page.evaluate(() => { Object.defineProperty(document, 'visibilityState', { configurable: true, value: 'visible' }); document.dispatchEvent(new Event('visibilitychange')) })
  await page.clock.runFor(30_500)
  await expect(page.getByRole('button', { name: 'Saya sudah membaca' })).toBeEnabled()
})

test('reading page fits desktop and mobile and remains usable if browser storage fails', async ({ page }, testInfo) => {
  await page.addInitScript(() => {
    Storage.prototype.getItem = () => { throw new DOMException('Denied', 'SecurityError') }
    Storage.prototype.setItem = () => { throw new DOMException('Denied', 'SecurityError') }
  })
  await page.clock.install()
  await page.goto('/latih/')
  await expect(page.getByRole('heading', { name: 'Sebelum mulai belajar' })).toBeVisible()
  for (const width of [1280, 390, 320]) {
    await page.setViewportSize({ width, height: 844 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    const button = await page.getByRole('button', { name: 'Saya sudah membaca' }).boundingBox()
    expect(button!.y + button!.height).toBeLessThanOrEqual(844)
    if (width === 390) await page.screenshot({ path: testInfo.outputPath('required-guide-mobile.png') })
  }
  await page.clock.runFor(60_500)
  await page.getByRole('button', { name: 'Saya sudah membaca' }).click()
  await expect(page.getByRole('heading', { name: 'Beranda', exact: true })).toBeVisible()
})

test('clearing site local data invalidates leftover timer from the same tab', async ({ page }) => {
  await page.clock.install()
  await page.goto('/latih/')
  await expect(page.getByRole('heading', { name: 'Sebelum mulai belajar' })).toBeVisible()
  await page.clock.runFor(30_000)
  await page.evaluate(() => localStorage.clear())
  await page.reload()
  const button = page.getByRole('button', { name: 'Saya sudah membaca' })
  await expect(button).toBeDisabled()
  expect(Number(await page.getByRole('progressbar').getAttribute('value'))).toBeLessThan(1000)
  await page.clock.runFor(60_500)
  await button.click()
  expect(await page.evaluate(() => sessionStorage.getItem('latih:guide-elapsed:v1'))).toBeNull()
  await page.evaluate(() => localStorage.clear())
  await page.reload()
  await expect(button).toBeDisabled()
  expect(Number(await page.getByRole('progressbar').getAttribute('value'))).toBeLessThan(1000)
})

test('old numeric completed timer cannot unlock the first guide', async ({ page }) => {
  await page.addInitScript(() => sessionStorage.setItem('latih:guide-elapsed:v1', '60000'))
  await page.goto('/latih/')
  await expect(page.getByRole('button', { name: 'Saya sudah membaca' })).toBeDisabled()
  expect(Number(await page.getByRole('progressbar').getAttribute('value'))).toBeLessThan(1000)
})
