test('invalid last opened data and failed saves do not block learning', async ({ page }) => {
  await page.addInitScript(() => {
    localStorage.setItem('latih:last-opened:v1', JSON.stringify({ version: 1, collection: { title: 'Rusak' } }))
    const set = Storage.prototype.setItem
    Storage.prototype.setItem = function (...args) {
      if (args[0] === 'latih:last-opened:v1') throw new DOMException('Full', 'QuotaExceededError')
      return set.apply(this, args)
    }
  })
  await page.goto('/latih/#beranda')
  await expect(page.getByRole('heading', { name: 'Beranda', exact: true })).toBeVisible()
  await expect(page.locator('.latih-last-opened')).toHaveCount(0)
  await page.getByRole('link', { name: 'Koleksi', exact: true }).click()
  await page.locator('[data-slot="card"]').filter({ hasText: 'Kosakata sehari-hari' }).getByRole('button', { name: 'Mulai latihan' }).click()
  await expect(page.getByRole('heading', { name: 'Curious', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Kembali ke koleksi', exact: true }).click()
  await page.getByRole('link', { name: 'Beranda', exact: true }).click()
  await expect(page.locator('.latih-last-opened')).toContainText('Kosakata sehari-hari')
})


