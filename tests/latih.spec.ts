test('mobile quiz retains the current panel throughout its closing animation', async ({ page }, testInfo) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/latih/koleksi')
  // Slow only the exit animation so transient content is observable on either engine.
  await page.addStyleTag({ content: '.latih-quiz-sheet[data-closed] { animation-duration: 1s !important; }' })
  await page.getByRole('button', { name: 'Impor soal', exact: true }).click()
  await page.getByLabel('JSON latihan').fill(JSON.stringify({ title: 'Transisi panel', type: 'multiple-choice', questions: [
    { question: 'Pertanyaan pertama', options: ['Satu', 'Dua'], answer: 0, hint: 'Petunjuk pertama.', explanation: 'Pembahasan pertama.' },
    { question: 'Pertanyaan kedua', options: ['Tiga', 'Empat'], answer: 1, explanation: 'Pembahasan kedua.' },
  ] }))
  await page.getByRole('button', { name: 'Tambahkan koleksi' }).click()
  await page.locator('[data-slot="card"]').filter({ hasText: 'Transisi panel' }).getByRole('button', { name: 'Mulai latihan' }).click()
  const sheet = page.locator('.latih-quiz-sheet')
  await page.getByRole('button', { name: 'Petunjuk', exact: true }).click()
  await expect(sheet).toContainText('Petunjuk pertama.')
  await sheet.getByRole('button', { name: 'Kembali ke soal', exact: true }).click()
  await expect(sheet).toHaveAttribute('data-closed', '')
  await expect(sheet).toContainText('Petunjuk pertama.')
  await expect(sheet).not.toContainText('Pembahasan pertama.')
  await expect(sheet).toBeHidden()
  await page.locator('.latih-answer').first().click()
  await page.getByRole('button', { name: 'Periksa jawaban', exact: true }).click()
  await sheet.getByRole('button', { name: 'Perluas', exact: true }).click()
  await sheet.getByRole('button', { name: 'Berikutnya', exact: true }).click()
  await expect(sheet).toHaveAttribute('data-closed', '')
  await expect(sheet).toHaveAttribute('data-expanded', 'true')
  await expect(sheet).toContainText('Pembahasan pertama.')
  await expect(sheet).toContainText('Benar, kamu sudah paham.')
  await expect(sheet).not.toContainText('Pembahasan kedua.')
  await page.screenshot({ path: testInfo.outputPath('closing-explanation-mobile.png') })
  await expect(sheet).toBeHidden()
  await expect(page.getByRole('region', { name: 'Teks soal' })).toContainText('Pertanyaan kedua')
  await page.reload()
  await expect(sheet).toHaveCount(0)
  await page.locator('.latih-answer').last().click()
  await page.getByRole('button', { name: 'Periksa jawaban', exact: true }).click()
  await expect(sheet).toContainText('Pembahasan kedua.')
  await sheet.getByRole('button', { name: 'Selesaikan sesi', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Sesi selesai.' })).toBeVisible()
  await expect(page.getByText('2 dari 2 jawaban benar.')).toBeVisible()
})

